    selected_ending = random.choice(ENDINGS_DATA)

    trope_A = breeds_data[breed_A]['trope']
    trope_B = breeds_data[breed_B]['trope']

    # 결말 텍스트 생성
    if is_hybrid:
        dynamic_ending_text = (f"【{selected_ending['title']}】 "
                               f"겉모습은 {breed_A}였으나 결국 {breed_B}의 "
                               f"<{trope_B}> 본능이 폭발하여, {selected_ending['desc']}")
    else:
        dynamic_ending_text = (f"【{selected_ending['title']}】 "
                               f"{breed_A} 특유의 <{trope_A}> 본능이 극단적으로 발현되어, "
                               f"{selected_ending['desc']}")

    # 🌟 에피소드 진행도 계산 (flow_type="hybrid" 곡선)
    episodes = []
    text_lines = []

    text_lines.append("=" * 85)
    text_lines.append("🌸 [라노벨 여주인공 9구역 타락 매트릭스 시뮬레이터] 🌸")
    text_lines.append("=" * 85)

    if is_hybrid:
        text_lines.append(f"🐾 모에 속성 : {breed_A}({trope_A}) ➡️ "
                          f"{breed_B}({trope_B}) [하이브리드!]")
    else:
        text_lines.append(f"🐾 모에 속성 : {breed_A}({trope_A}) [단일 속성]")

    text_lines.append(f"📊 초기값     : H:{start_H} / L:{start_L}")
    text_lines.append(f"🎬 진행 루트  : HYBRID 루트")
    text_lines.append("=" * 85)

    for i in range(num_episodes):
        # 진행 비율 계산
        if num_episodes <= 1:
            t = 1.0
        else:
            t = i / (num_episodes - 1)

        # 마지막 에피소드는 강제로 H:5, L:5로 고정 (결말)
        if i == num_episodes - 1:
            cur_H, cur_L = 5, 5
        else:
            # hybrid 곡선: H와 L 모두 선형
            cur_H = start_H + (5 - start_H) * t
            cur_L = start_L + (5 - start_L) * t
            cur_H, cur_L = round(cur_H), round(cur_L)

        # 범주 결정
        h_cat = _get_category(cur_H)
        l_cat = _get_category(cur_L)

        # stage_name 및 section_tag
        stage_name = _get_stage_name(h_cat, l_cat)
        section_tag = _get_section_tag(t)

        # 하이브리드: active_breed 결정 (cur_H >= 3 or cur_L >= 3 시 breed_B)
        if is_hybrid and (cur_H >= 3 or cur_L >= 3):
            active_breed = breed_B
        else:
            active_breed = breed_A

        # 9구역 matrix에서 묘사 추출
        animal_desc = breeds_data[active_breed]["matrix"][f"L_{l_cat}"][f"H_{h_cat}"]
        matrix_desc = MATRIX_DESCRIPTIONS[f"L_{l_cat}"][f"H_{h_cat}"]

        # breed 태그
        if is_hybrid:
            if cur_H < 3 and cur_L < 3:
                breed_tag = breed_A
            else:
                breed_tag = f"겉은 {breed_A}인데 속은 {breed_B}인"
        else:
            breed_tag = breed_A

        # 마지막 에피소드: breed_tag 덮어쓰기
        if i == num_episodes - 1:
            breed_tag = f"완전히 타락한 {breed_B}" if is_hybrid else f"완전히 타락한 {breed_A}"

        # 에피소드 데이터 저장
        episode_data = {
            "index": i + 1,
            "t": t,
            "cur_H": cur_H,
            "cur_L": cur_L,
            "h_cat": h_cat,
            "l_cat": l_cat,
            "stage_name": stage_name,
            "section_tag": section_tag,
            "active_breed": active_breed,
            "animal_desc": animal_desc,
            "matrix_desc": matrix_desc,
            "breed_tag": breed_tag,
        }
        episodes.append(episode_data)

        # 텍스트 빌드
        text_lines.append("")
        text_lines.append(f"📖 [Ep.{i+1:02d}] <{stage_name}> "
                          f"[H:{cur_H} / L:{cur_L}]")
        text_lines.append(f"행동 묘사 : {animal_desc}")
        text_lines.append(f"심리 상태 : {matrix_desc}")
        if i == num_episodes - 1:
            text_lines.append(f"결말 유형 : {dynamic_ending_text}")
        text_lines.append(f"[{breed_tag}]")

    persona_text = "\n".join(text_lines)

    # 출력 (표시용)
    print(persona_text)

    # 구조화된 데이터 반환
    return {
        "breed_A": breed_A,
        "breed_B": breed_B,
        "is_hybrid": is_hybrid,
        "trope_A": trope_A,
        "trope_B": trope_B,
        "start_H": start_H,
        "start_L": start_L,
        "selected_ending": selected_ending,
        "dynamic_ending_text": dynamic_ending_text,
        "episodes": episodes,
        "persona_text": persona_text,
    }


