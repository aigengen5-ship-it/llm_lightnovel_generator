def _get_category(score):
    """H/L score를 low/mid/high 범주로 변환"""
    if score <= 1:
        return "low"
    elif score <= 3:
        return "mid"
    else:
        return "high"


def _get_stage_name(h_cat, l_cat):
    """9구역 범주를 기존 stage_names로 매핑"""
    if l_cat == "high" and h_cat == "high":
        return "권속화"
    elif l_cat == "high":
        return "집착"
    elif h_cat == "high":
        return "애정"
    elif h_cat == "mid" or l_cat == "mid":
        return "친밀"
    elif h_cat == "low" and l_cat == "low":
        return "경계"
    else:
        return "혐오"


