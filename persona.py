def get_stage_description(breed_name: str, stage_idx: int) -> str:
    """
    품종 이름과 단계 인덱스(0~5)로 해당 단계의 matrix 묘사를 반환.
    theme_gen_auto.py 등 외부 모듈에서 사용.

    Args:
        breed_name: BREEDS_DATA의 키 (예: "곰", "여우")
        stage_idx: 0~5 단계 인덱스

    Returns:
        해당 단계의 동물 묘사 텍스트

    Raises:
        KeyError: 존재하지 않는 품종 이름
        IndexError: 유효하지 않은 stage_idx
    """
    if breed_name not in BREEDS_DATA:
        raise KeyError(f"존재하지 않는 품종: {breed_name}")
    if stage_idx < 0 or stage_idx > 5:
        raise IndexError(f"stage_idx는 0~5 범위여야 함: {stage_idx}")

    l_cat, h_cat = _STAGE_TO_MATRIX_MAP[stage_idx]
    return BREEDS_DATA[breed_name]["matrix"][l_cat][h_cat]


